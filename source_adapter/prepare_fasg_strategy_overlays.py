def instrument_source_core_budget(source: str) -> str:
    """Bound the original tiler's compile-info AIV/AIC input when requested.

    The source strategy still owns every generated tiling field.  Invalid
    inputs fail closed; they never fall back to a default candidate.
    """
    if CORE_BUDGET_SENTINEL in source:
        return source
    original = """    compileInfoPtr->aivNum = ascendcPlatform.GetCoreNumAiv();
    compileInfoPtr->aicNum = ascendcPlatform.GetCoreNumAic();"""
    replacement = r"""    compileInfoPtr->aivNum = ascendcPlatform.GetCoreNumAiv();
    compileInfoPtr->aicNum = ascendcPlatform.GetCoreNumAic();
    // FASG_SOURCE_AIV_CAP_V1: a finite source-input candidate axis. It never
    // edits a tiling after an original strategy has produced it.
    const char *requestedAivText = std::getenv("FASG_SOURCE_AIV_CAP");
    if (requestedAivText != nullptr) {
        errno = 0;
        char *parseEnd = nullptr;
        const unsigned long long requestedAiv = std::strtoull(requestedAivText, &parseEnd, 10);
        const uint64_t runtimeAiv = compileInfoPtr->aivNum;
        const uint64_t runtimeAic = compileInfoPtr->aicNum;
        if (errno != 0 || parseEnd == requestedAivText || *parseEnd != '\0' || requestedAiv == 0ULL ||
            requestedAiv > runtimeAiv || runtimeAiv == 0ULL || runtimeAic == 0ULL || runtimeAic % runtimeAiv != 0ULL) {
            OPS_LOG_E(context, "invalid source AIV cap: %s (runtime aiv=%lu aic=%lu)", requestedAivText,
                      runtimeAiv, runtimeAic);
            return ge::GRAPH_FAILED;
        }
        const uint64_t aicPerAiv = runtimeAic / runtimeAiv;
        compileInfoPtr->aivNum = static_cast<uint64_t>(requestedAiv);
        compileInfoPtr->aicNum = static_cast<uint64_t>(requestedAiv) * aicPerAiv;
    }
    // FASG_SOURCE_L2_CAP_V1: optional hardware-envelope heuristic. A smaller
    // source-visible L2 budget is always no larger than physical L2, so every
    // original-formula tiling produced here remains capacity-feasible on the
    // target. It is intentionally not a claim about measured L2 placement.
    const char *l2DivisorText = std::getenv("FASG_SOURCE_L2_DIVISOR");
    if (l2DivisorText != nullptr) {
        errno = 0;
        char *parseEnd = nullptr;
        const unsigned long long divisor = std::strtoull(l2DivisorText, &parseEnd, 10);
        const uint64_t runtimeL2 = compileInfoPtr->l2CacheSize;
        if (errno != 0 || parseEnd == l2DivisorText || *parseEnd != '\0' ||
            (divisor != 1ULL && divisor != 2ULL && divisor != 4ULL && divisor != 8ULL) ||
            runtimeL2 == 0ULL || runtimeL2 / divisor == 0ULL) {
            OPS_LOG_E(context, "invalid source L2 divisor: %s (runtime l2=%lu)", l2DivisorText, runtimeL2);
            return ge::GRAPH_FAILED;
        }
        compileInfoPtr->l2CacheSize = runtimeL2 / divisor;
    }"""
    if source.count(original) != 1:
        raise RuntimeError("cannot locate original FASG compile-info core assignment")
    return source.replace(original, replacement)


def digest(path: Path) -> str:
    value = hashlib.sha256()
    with path.open("rb") as source:
        for part in iter(lambda: source.read(1024 * 1024), b""):
            value.update(part)
    return value.hexdigest()


def run(argv: list[str]) -> str:
    result = subprocess.run(argv, capture_output=True, text=True, check=False)
    if result.returncode:
        raise RuntimeError("command failed rc={} argv={} stderr={}".format(
            result.returncode, " ".join(argv), result.stderr.strip()))
    return result.stdout.strip()


@dataclass(frozen=True)
class Registration:
    relative_path: Path
    start: int
    end: int
    source_class: str
    priority: int
    text: str


def find_close(text: str, opening: int) -> int:
    """Return the index one past `);` for a registration macro invocation."""
    depth = 0
    quote: str | None = None
    escaped = False
    for index in range(opening, len(text)):
        char = text[index]
        if quote:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = None
            continue
        if char in ("'", '\"'):
            quote = char
        elif char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth == 0:
                cursor = index + 1
                while cursor < len(text) and text[cursor].isspace():
                    cursor += 1
                if cursor >= len(text) or text[cursor] != ";":
                    raise RuntimeError("registration macro is missing trailing semicolon")
                return cursor + 1
    raise RuntimeError("unterminated registration macro")


def registrations(source_root: Path) -> list[Registration]:
    op_root = source_root / OP["relative_root"] / "ophost"
    start_pattern = re.compile(re.escape(MACRO) + r"\s*\(")
    class_pattern = re.compile(
        r"^" + re.escape(MACRO) + r"\s*\(\s*\"" + re.escape(OPERATOR) +
        r"\"\s*,\s*([A-Za-z_][A-Za-z0-9_]*)\s*,\s*([0-9]+)\s*\);$",
        re.DOTALL,
    )
    output: list[Registration] = []
    for path in sorted(op_root.glob("*.cpp")):
        content = path.read_text(encoding="utf-8")
        for match in start_pattern.finditer(content):
            end = find_close(content, content.find("(", match.start()))
            invocation = content[match.start():end]
            parsed = class_pattern.match(invocation.strip())
            if not parsed:
                continue
            output.append(Registration(
                relative_path=path.relative_to(source_root),
                start=match.start(), end=end,
                source_class=parsed.group(1), priority=int(parsed.group(2)), text=invocation,
            ))
    output.sort(key=lambda row: (row.priority, row.source_class), reverse=True)
    return output


def require_pinned_source(source_root: Path) -> list[Registration]:
    require_repo_source_bundle(source_root, "cann_ops_adv", SOURCE["commit"])
    for relative, expected in OP["pinned_files"].items():
        actual = digest(source_root / OP["relative_root"] / relative)
        if actual != expected:
            raise RuntimeError("pinned source hash mismatch: {}".format(relative))
    rows = registrations(source_root)
    if len(rows) != OP["expected_strategy_count"]:
        raise RuntimeError("unexpected original strategy count: expected={} actual={}".format(
            OP["expected_strategy_count"], len(rows)))
    return rows


def overlay_source(text: str, rows: list[Registration], selected: Registration, relative: Path) -> str:
    local = [row for row in rows if row.relative_path == relative]
    for row in sorted(local, key=lambda item: item.start, reverse=True):
        if row == selected:
            continue
        replacement = "/* source-candidate collector disabled registration: {} priority={} */".format(
            row.source_class, row.priority)
        text = text[:row.start] + replacement + text[row.end:]
    return text


def allowed_overlay_source(before: str, rows: list[Registration], selected: Registration,
                           relative: Path) -> str:
    """Return the only permitted source content for one overlay file."""
    after = overlay_source(before, rows, selected, relative)
    if relative == ENTRY_RELATIVE:
        after = instrument_source_core_budget(instrument_entry_source(after))
    return after


def existing_overlay(source_root: Path, output: Path, selected: Registration,
                     rows: list[Registration], harness_text: str,
                     harness_provenance: dict[str, object]) -> dict[str, object] | None:
    """Return a verified existing overlay, or None when it has not been made.

    This makes a stopped source-preparation stage resumable without accepting a
    partially edited worktree. Every registration source, the audit entry, and
    the attested source-build harness must still equal their allowed
    transformations exactly.
    """
    if not output.exists():
        return None
    manifest_path = output / "source_candidate_overlay.json"
    if not manifest_path.is_file():
        raise RuntimeError("existing overlay has no provenance manifest: {}".format(output))
    metadata = json.loads(manifest_path.read_text(encoding="utf-8"))
    required = {
        "source_family": "cann_ops_adv",
        "cmake_op_name": "flash_attention_score_grad",
        "audit_entry_relative": str(ENTRY_RELATIVE),
        "audit_sentinel": AUDIT_SENTINEL,
        "official_commit": SOURCE["commit"],
        "strategy_class": selected.source_class,
        "strategy_priority": selected.priority,
        "strategy_algorithm_changes": False,
        "kernel_algorithm_changes": False,
        "source_compile_info_core_budget_enumeration": True,
        "source_hardware_envelope_heuristic_enumeration": True,
        "hardware_envelope_heuristic": {
            "enabled": True, "environment": "FASG_SOURCE_L2_DIVISOR", "audit_field": "l2_cap_divisor",
            "resource": "source_visible_l2_scheduling_budget", "divisors": [2, 4, 8], "max_anchors": 16,
        },
    }
    if any(metadata.get(key) != value for key, value in required.items()):
        raise RuntimeError("existing overlay provenance does not match requested strategy: {}".format(output))
    affected = {row.relative_path for row in rows} | {ENTRY_RELATIVE}
    for relative in sorted(affected):
        expected = allowed_overlay_source((source_root / relative).read_text(encoding="utf-8"), rows, selected, relative)
        actual = (output / relative).read_text(encoding="utf-8")
        if actual != expected:
            raise RuntimeError("existing overlay source differs outside the allowed registration isolation: {}".format(
                output / relative))
    generated_harness = output / "CMakeLists.txt"
    if not generated_harness.is_file() or generated_harness.read_text(encoding="utf-8") != harness_text:
        raise RuntimeError("existing overlay build harness differs from its pinned allowed transformation: {}".format(
            generated_harness))
    if metadata.get("build_harness") != harness_provenance:
        raise RuntimeError("existing overlay build-harness provenance differs from the pinned source")
    materialize_build_support_files(output, None, harness_provenance)
    metadata["resumed_existing_overlay"] = True
    return metadata


def write_overlay(source_root: Path, output_parent: Path, selected: Registration, rows: list[Registration],
                  harness_root: Path, harness_text: str,
                  harness_provenance: dict[str, object]) -> dict[str, object]:
    output = output_parent / ("fasg_" + selected.source_class.lower())
    existing = existing_overlay(source_root, output, selected, rows, harness_text, harness_provenance)
    if existing is not None:
        return existing
    run(["git", "-C", str(source_root), "worktree", "add", "--detach", str(output), "HEAD"])
    changed: list[dict[str, str]] = []
    affected = {row.relative_path for row in rows} | {ENTRY_RELATIVE}
    for relative in sorted(affected):
        target = output / relative
        before = target.read_text(encoding="utf-8")
        after = allowed_overlay_source(before, rows, selected, relative)
        if before != after:
            target.write_text(after, encoding="utf-8")
            changed.append({
                "path": str(relative),
                "kind": "source_tiling_observation_and_core_budget" if relative == ENTRY_RELATIVE else "registration_isolation",
                "sha256_before": hashlib.sha256(before.encode("utf-8")).hexdigest(),
                "sha256_after": digest(target),
            })
    (output / "CMakeLists.txt").write_text(harness_text, encoding="utf-8")
    materialize_build_support_files(output, harness_root, harness_provenance)
    status = run(["git", "-C", str(output), "status", "--porcelain", "--untracked-files=no"])
    metadata: dict[str, object] = {
        "schema": "fasg_original_strategy_overlay_v1",
        "operator": OPERATOR,
        "source_family": "cann_ops_adv",
        "cmake_op_name": "flash_attention_score_grad",
        "audit_entry_relative": str(ENTRY_RELATIVE),
        "audit_sentinel": AUDIT_SENTINEL,
        "official_url": SOURCE["url"],
        "official_tag": SOURCE["tag"],
        "official_commit": SOURCE["commit"],
        "strategy_class": selected.source_class,
        "strategy_priority": selected.priority,
        "enabled_registration": selected.text,
        "disabled_original_registrations": [
            {"class": row.source_class, "priority": row.priority}
            for row in rows if row != selected
        ],
        "overlay": str(output),
        "source_status": status.splitlines(),
        "modified_registration_files": changed,
        "instrumentation": {
            "enabled": True,
            "audit_schema": "fasg_raw_tiling_observation_v1",
            "audit_environment": "FASG_TILING_AUDIT_PATH",
            "source_budget_environment": "FASG_SOURCE_AIV_CAP",
            "scope": "FASG entry return status plus raw tiling provenance; a finite AIV/AIC source budget and optional smaller L2 scheduling envelope are accepted before the original strategy runs",
            "mechanism": "write one JSON line only when FASG_TILING_AUDIT_PATH is supplied; read FASG_SOURCE_AIV_CAP and optional FASG_SOURCE_L2_DIVISOR only in TilingPrepareForFlashAttentionScoreGrad",
            "mutates_tiling_context": False,
        },
        "strategy_algorithm_changes": False,
        "kernel_algorithm_changes": False,
        "source_compile_info_core_budget_enumeration": True,
        "source_hardware_envelope_heuristic_enumeration": True,
        "hardware_envelope_heuristic": {
            "enabled": True, "environment": "FASG_SOURCE_L2_DIVISOR", "audit_field": "l2_cap_divisor",
            "resource": "source_visible_l2_scheduling_budget", "divisors": [2, 4, 8], "max_anchors": 16,
        },
        "build_scope": harness_provenance["build_scope"],
        "candidate_rule": "run this original strategy for each finite runtime-derived AIV/AIC source budget; only if that complete original-source set is below the group minimum, rerun selected source contexts with the finite L2 divisors 2/4/8. Deduplicate only exact observed raw tiling identities and retain only later output-validated executions",
        "build_harness": harness_provenance,
        "forbidden": LOCK["collection_contract"]["forbidden"],
    }
    (output / "source_candidate_overlay.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return metadata


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", required=True, type=Path)
    parser.add_argument("--harness-root", required=True, type=Path,
                        help="pinned public cann-ops tree that supplies the missing advanced-tree build harness")
    parser.add_argument("--output-parent", required=True, type=Path,
                        help="existing directory outside this repository")
    parser.add_argument("--strategy", action="append", default=[],
                        help="original strategy class to prepare; repeatable (default: all)")
    args = parser.parse_args()
    if not args.output_parent.is_dir():
        raise RuntimeError("output parent does not exist: {}".format(args.output_parent))
    rows = require_pinned_source(args.source_root)
    harness_text, harness_provenance = source_build_harness(args.harness_root, "flash_attention_score_grad")
    allowed = {row.source_class for row in rows}
    requested = set(args.strategy) if args.strategy else allowed
    unknown = sorted(requested - allowed)
    if unknown:
        raise RuntimeError("unknown original strategy: {}".format(", ".join(unknown)))
    prepared = [write_overlay(args.source_root, args.output_parent, row, rows, args.harness_root, harness_text, harness_provenance)
                for row in rows if row.source_class in requested]
    print(json.dumps({
        "schema": "fasg_original_strategy_overlay_batch_v1",
        "matmul_included": False,
        "prepared_count": len(prepared),
        "original_registered_strategy_count": len(rows),
        "overlays": prepared,
    }, ensure_ascii=False, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except RuntimeError as error:
        print("source-candidate error: {}".format(error), file=sys.stderr)
        sys.exit(2)

#!/usr/bin/env python3
"""Create source-rule candidate overlays for FlashAttentionScoreGrad.

Each overlay is a new git worktree at the pinned public source revision.  It
keeps exactly one original `REGISTER_TILING_TEMPLATE` registration and disables
the other registrations. No strategy class, predicate, kernel, or generated
tiling field is changed. The collector may bound the source compile-info
AIV/AIC core budget through ``FASG_SOURCE_AIV_CAP`` before the original
strategy runs. The matching AIC budget is derived from the platform's original
AIC:AIV ratio. This is a finite source-input candidate axis, not a hand-built
tiling or a mutation of raw tiling after source generation. If that complete
original-source collection has fewer than the required distinct tilings, a
separately labelled L2-envelope divisor may reduce only the source-visible L2
scheduling budget. The resulting tile still has to fit the actual, larger
physical L2 and is generated by the original source calculation.

The FASG entry has one audit-only status passthrough: after the original
dispatcher returns, it records the already-generated raw tiling identity only
when a temporary audit-path environment variable is set. It never changes the
context or return status. Therefore a failed overlay means that the chosen
original strategy rejected that source context; it is not converted into a
synthetic candidate.

The public 8.1 advanced tree intentionally has no top-level CMakeLists.txt.
For an executable package it therefore receives an attested build harness
derived from the pinned public ``cann-ops`` root CMake file, changing only its
``src/common`` utility path to this tree's ``src/utils`` path.  This harness
does not alter tiler/kernel source.  This script only creates source overlays
and JSON manifests.  It neither downloads source nor compiles, launches,
resets, or otherwise calls an NPU.
"""

